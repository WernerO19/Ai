import React, { useState } from 'react';
import { DeliverableFile, DotId } from '../types/swarm';
import { 
  Download, Copy, Check, Edit3, Save, FileText, 
  ExternalLink, Sparkles, RefreshCw, Layers, CheckCircle2 
} from 'lucide-react';
import { downloadTextFile } from '../utils/fileDownload';
import { audioService } from '../services/audio';
import { DotBlobAvatar } from './DotBlobAvatar';

interface DeliverableCanvasProps {
  activeFile: DeliverableFile | null;
  onSaveFile: (file: DeliverableFile) => void;
  activeDotId: DotId;
  onDownloadAll?: () => void;
}

export const DeliverableCanvas: React.FC<DeliverableCanvasProps> = ({
  activeFile,
  onSaveFile,
  activeDotId,
}) => {
  const [isEditing, setIsEditing] = useState(false);
  const [content, setContent] = useState(activeFile?.content || '');
  const [copied, setCopied] = useState(false);

  // Sync content when activeFile changes
  React.useEffect(() => {
    if (activeFile) {
      setContent(activeFile.content);
      setIsEditing(false);
    }
  }, [activeFile?.id]);

  const handleDownload = () => {
    if (!activeFile) return;
    downloadTextFile(activeFile.name, content, activeFile.mimeType || 'text/plain');
    audioService.playChirp('success');
  };

  const handleCopy = () => {
    if (!activeFile) return;
    navigator.clipboard.writeText(content);
    setCopied(true);
    audioService.playChirp('chirp');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleSave = () => {
    if (!activeFile) return;
    const updated: DeliverableFile = {
      ...activeFile,
      content,
      size: new Blob([content]).size,
    };
    onSaveFile(updated);
    setIsEditing(false);
    audioService.playChirp('success');
  };

  if (!activeFile) {
    return (
      <div className="h-full flex flex-col items-center justify-center p-8 text-center bg-[#faf9f5]">
        <div className="w-16 h-16 rounded-2xl bg-amber-100 flex items-center justify-center text-amber-600 mb-4 shadow-sm">
          <FileText className="w-8 h-8" />
        </div>
        <h3 className="font-semibold text-zinc-800 text-base">No active document</h3>
        <p className="text-zinc-500 text-xs max-w-sm mt-1 mb-6 leading-relaxed">
          Ask your Dot in the chat on the left (e.g. &quot;Send me a funny note&quot; or &quot;Draft a proposal&quot;) to produce a live document deliverable here.
        </p>

        {/* Floating Peeking Dot from OpenAI Screenshot */}
        <div className="flex items-center gap-3 p-3.5 rounded-2xl bg-white border border-stone-200/80 shadow-sm max-w-xs">
          <DotBlobAvatar dotId={activeDotId} size="md" />
          <div className="text-left">
            <span className="block text-xs font-semibold text-zinc-800">Your Dot is standing by</span>
            <span className="text-[11px] text-zinc-500">Ready to author docs, code, and notes</span>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="h-full flex flex-col bg-[#faf9f5] relative overflow-hidden select-text">
      {/* Document Workspace Top Bar */}
      <div className="flex items-center justify-between px-5 py-3 border-b border-stone-200/90 bg-white">
        <div className="flex items-center gap-3">
          <div className="w-7 h-7 rounded-lg bg-amber-500/10 border border-amber-500/20 flex items-center justify-center text-amber-700">
            <FileText className="w-4 h-4" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <span className="font-medium text-xs text-zinc-900 tracking-tight font-mono">
                {activeFile.name}
              </span>
              <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-stone-100 text-stone-600 border border-stone-200">
                {activeFile.size} bytes
              </span>
            </div>
            <span className="text-[11px] text-zinc-400">
              Live deliverable generated by {activeFile.generatedBy}
            </span>
          </div>
        </div>

        {/* Primary Action Buttons */}
        <div className="flex items-center gap-2">
          {/* One-click Download button */}
          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-full bg-zinc-900 hover:bg-zinc-800 text-white font-medium text-xs transition-colors shadow-sm cursor-pointer"
            title="Download this file to your computer"
          >
            <Download className="w-3.5 h-3.5 stroke-[2.5]" />
            <span>Download File</span>
          </button>

          {/* Copy Button */}
          <button
            onClick={handleCopy}
            className="flex items-center gap-1 px-3 py-1.5 rounded-full bg-white hover:bg-stone-50 border border-stone-200 text-zinc-700 text-xs font-medium transition-colors cursor-pointer"
            title="Copy content"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied' : 'Copy'}</span>
          </button>

          {/* Edit / Save Button */}
          {isEditing ? (
            <button
              onClick={handleSave}
              className="flex items-center gap-1 px-3 py-1.5 rounded-full bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-medium transition-colors cursor-pointer"
            >
              <Save className="w-3.5 h-3.5" />
              <span>Save</span>
            </button>
          ) : (
            <button
              onClick={() => setIsEditing(true)}
              className="flex items-center gap-1 px-3 py-1.5 rounded-full bg-white hover:bg-stone-50 border border-stone-200 text-zinc-700 text-xs font-medium transition-colors cursor-pointer"
            >
              <Edit3 className="w-3.5 h-3.5" />
              <span>Edit</span>
            </button>
          )}
        </div>
      </div>

      {/* Main Document Content Canvas */}
      <div className="flex-1 p-6 overflow-y-auto">
        <div className="max-w-2xl mx-auto bg-white rounded-2xl border border-stone-200/90 shadow-sm p-6 relative">
          {/* Document Header */}
          <div className="flex items-start justify-between gap-4 mb-4 pb-4 border-b border-stone-100">
            <div>
              <span className="text-[10px] font-mono tracking-wider uppercase text-amber-600 font-semibold block mb-1">
                Workspace Deliverable
              </span>
              <h2 className="text-xl font-bold text-zinc-900 tracking-tight">
                {activeFile.name.replace(/\.[^/.]+$/, "").replace(/_/g, " ")}
              </h2>
              <p className="text-xs text-zinc-500 mt-1">
                Authored by {activeFile.generatedBy.toUpperCase()} • Ready for export and deployment
              </p>
            </div>

            <div className="p-2 rounded-xl bg-amber-50 border border-amber-100">
              <DotBlobAvatar dotId={activeDotId} size="sm" />
            </div>
          </div>

          {/* Document Content / Editor */}
          {isEditing ? (
            <textarea
              value={content}
              onChange={(e) => setContent(e.target.value)}
              className="w-full h-80 p-4 rounded-xl bg-stone-50 border border-stone-200 font-mono text-xs text-zinc-800 focus:outline-none focus:border-zinc-400 leading-relaxed resize-none"
            />
          ) : (
            <div className="font-sans text-sm text-zinc-800 leading-relaxed whitespace-pre-wrap select-text p-2">
              {content}
            </div>
          )}

          {/* Quick Download Banner at the bottom of the document */}
          <div className="mt-8 pt-4 border-t border-stone-100 flex items-center justify-between">
            <span className="text-xs text-zinc-400 font-mono">
              Saved in local workspace • {activeFile.name}
            </span>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 text-xs text-zinc-900 hover:text-black font-semibold cursor-pointer underline underline-offset-2"
            >
              <Download className="w-3.5 h-3.5" />
              Download {activeFile.name}
            </button>
          </div>
        </div>
      </div>

      {/* Peeking Dot in Bottom Right (exactly like OpenAI screenshot!) */}
      <div className="absolute -bottom-4 -right-4 pointer-events-none opacity-90 transition-transform duration-300 hover:translate-y-[-10px]">
        <DotBlobAvatar dotId={activeDotId} size="lg" />
      </div>
    </div>
  );
};
